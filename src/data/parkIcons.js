// Файл иконки для эмодзи из данных парка или null, если подходящей нет.
export function parkIconSrc(emoji) {
  if (!emoji) return null;
  const key = String(emoji).replace(/️/g, '').trim();
  return PARK_EMOJI_ICONS[key] ?? null;
}
